def main():
    # 去重
    print("查询已有...")
    existing = set()
    try:
        for item in requests.get(API_LIST, timeout=15).json():
            q = (item.get('question') or '').strip()
            if q: existing.add(q)
    except: pass

    new_items = [d for d in DIALOGUES if d['question'] not in existing]
    skipped = len(DIALOGUES) - len(new_items)
    print(f"共{len(DIALOGUES)}条, 跳过{skipped}条, 待导入{len(new_items)}条")

    if not new_items: return print("全部已存在")

    # 导入
    ok = 0
    for i in range(0, len(new_items), 10):
        chunk = new_items[i:i+10]
        payload = [{
            "question": it["question"],
            "answer": it["answer"],
            "keywords": it["keywords"],
            "variants": it.get("variants",""),
            "category": it["category"],
            "priority": it["priority"],
            "enabled": 1,
        } for it in chunk]
        try:
            r = requests.post(API, json={"items": payload}, timeout=30)
            n = r.json().get('imported', len(chunk))
            ok += n
            print(f"  批次{i//10+1}: {n}条 OK")
        except Exception as e:
            print(f"  批次{i//10+1}: FAILED - {e}")

    print(f"\n导入完成: {ok}条")


if __name__ == '__main__':
    main()
