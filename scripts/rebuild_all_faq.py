csv_path = "D:/TourAI-Avatar/data/scenic_faq_questions.csv"

# Clean function
def clean(text):
    """Remove emoji, markdown symbols, and normalize"""
    import re
    # Remove common emoji ranges
    text = re.sub(r'[\U0001F300-\U0001F9FF]', '', text)
    text = re.sub(r'[\U0001FA00-\U0001FA6F]', '', text)
    text = re.sub(r'[☀-➿]', '', text)
    text = re.sub(r'[⭐❤✨⚡]', '', text)
    # Remove markdown bold/italic
    text = re.sub(r'\*\*', '', text)
    text = re.sub(r'\*', '', text)
    # Remove extra spaces
    text = re.sub(r'\s+', ' ', text).strip()
    return text

with open(csv_path, "w", encoding="utf-8", newline="") as f:
    writer = csv.writer(f)
    writer.writerow(["question", "answer"])
    for q, a in all_qa:
        writer.writerow([clean(q), clean(a)])

