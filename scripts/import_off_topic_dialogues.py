def main():
    # 1. 获取已有对话去重
    print("🔍 查询已有对话...")
    existing = set()
    try:
        resp = requests.get(API_LIST, timeout=15)
        for item in resp.json():
            q = (item.get('question') or '').strip()
            if q:
                existing.add(q)
    except Exception as e:
        print(f"  ⚠️  {e}")

    # 2. 去重
    new_items = [d for d in OFF_TOPIC if d['question'] not in existing]
    skipped = len(OFF_TOPIC) - len(new_items)
    print(f"  共 {len(OFF_TOPIC)} 条, 跳过 {skipped} 条已存在, 待导入 {len(new_items)} 条")

    if not new_items:
        print("✅ 全部已存在")
        return

    # 3. 输出 JSON
    json_out = []
    for it in new_items:
        json_out.append({
            "question": it["question"],
            "answer": it["answer"],
            "keywords": it["keywords"],
            "category": it["category"],
            "priority": it["priority"],
            "enabled": 1,
        })

    out_path = f"data/off_topic_dialogues.json"
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(json_out, f, ensure_ascii=False, indent=2)
    print(f"📄 JSON: {out_path} ({len(json_out)} 条)")

    # 4. 批量导入
    B = 50
    ok = 0
    for i in range(0, len(new_items), B):
        chunk = new_items[i:i+B]
        payload = [{
            "question": it["question"],
            "answer": it["answer"],
            "keywords": it["keywords"],
            "category": it["category"],
            "priority": it["priority"],
            "enabled": 1,
        } for it in chunk]
        try:
            r = requests.post(API, json={"items": payload}, timeout=30)
            n = r.json().get('imported', len(chunk))
            ok += n
            print(f"  第 {i//B+1} 批: {n} 条 OK")
        except Exception as e:
            print(f"  第 {i//B+1} 批: FAILED — {e}")

    print(f"\n🎉 导入完成: {ok} 条")
    print(f"   管理后台: http://localhost:5174 → 常用对话 → 闲聊问候")


if __name__ == '__main__':
    main()
